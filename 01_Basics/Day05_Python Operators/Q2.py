# Write a Python program that stores the length and breadth of a rectangle in variables.
# Use:
# - Length = 12
# - Breadth = 5
# Calculate and print:
# 1. The perimeter of the rectangle.
# 2. The area of the rectangle.
# 3. The difference between the perimeter and the area.
# Use separate variables for the three results.
Length = 12
Breadth = 5
p=2*(Length+Breadth)
a=Length*Breadth
d=a-p
print("the perimeter of rectangle is ",p)
print("the area of rectangle is ",a)
print("the difference of rectangle is ",d)